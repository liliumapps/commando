package shell

import "fmt"

const fishTemplate = `# commando shell integration (fish) - generated by 'commando init fish'
# Add to ~/.config/fish/config.fish:  commando init fish | source
#
# Commando reads shell history directly. This installs only the summon widget.

function __commando_widget
    set -l out (command commando search --print </dev/tty | string collect)
    if test -n "$out"
        commandline --replace -- "$out"
        commandline --cursor (string length -- "$out")
    end
    commandline -f repaint
end
bind \c%[1]c __commando_widget
bind -M insert \c%[1]c __commando_widget
`

// FishInit returns Fish line-editor integration for the configured control key.
func FishInit(keyBinding string) string {
	return fmt.Sprintf(fishTemplate, controlKey(keyBinding))
}
