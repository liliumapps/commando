package shell

import "fmt"

const bashTemplate = `# commando shell integration (bash) - generated by 'commando init bash'
# Add to ~/.bashrc:  eval "$(commando init bash)"
#
# Commando reads shell history directly. This installs only the summon widget.

__commando_widget() {
  local out
  out="$(command commando search --print </dev/tty)"
  if [[ -n "$out" ]]; then
    READLINE_LINE="$out"
    READLINE_POINT=${#READLINE_LINE}
  fi
}
bind -m emacs-standard -x '"\C-%[1]c":__commando_widget'
bind -m vi-insert -x '"\C-%[1]c":__commando_widget'
bind -m vi-command -x '"\C-%[1]c":__commando_widget'
`

// BashInit returns Bash Readline integration for the configured control key.
func BashInit(keyBinding string) string {
	return fmt.Sprintf(bashTemplate, controlKey(keyBinding))
}
