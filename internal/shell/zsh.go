// Package shell emits summon widgets that connect commando to the native line
// editors in Zsh, Bash, and Fish.
package shell

import "fmt"

// zshTemplate is the zsh integration script. It is parameterised by the key
// binding and binds a ZLE widget that opens the picker and places the chosen
// command on the current line for review (it is not executed automatically).
//
// %[1]s is replaced by the key binding (e.g. "^G").
const zshTemplate = `# commando shell integration (zsh) — generated by 'commando init zsh'
# Add to ~/.zshrc:  eval "$(commando init zsh)"
#
# commando reads your shell history file directly, so no capture hook is
# installed — only the summon widget below.

# --- summon widget ---
__commando_widget() {
  local out
  out="$(command commando search --print </dev/tty)"
  if [[ -n $out ]]; then
    BUFFER="$out"
    CURSOR=${#BUFFER}
  fi
  zle reset-prompt
}
zle -N __commando_widget
bindkey '%[1]s' __commando_widget
# --- end commando ---
`

// ZshInit returns the zsh integration script with the given key binding. An
// empty keyBinding defaults to Ctrl-G.
func ZshInit(keyBinding string) string {
	return fmt.Sprintf(zshTemplate, caretBinding(keyBinding))
}
